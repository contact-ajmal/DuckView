#!/usr/bin/env node
/**
 * Regenerates packages/server/src/services/mosaic-names.ts — the vocabulary of Mosaic specs (marks, plot attributes,
 * interactors, legends, inputs, transforms, selection types) taken from the installed @uwdata/vgplot and
 * @uwdata/mosaic-spec. The server validates specs against these names without loading the browser stack
 * (mosaic-core drags DuckDB-WASM along). Run after bumping the Mosaic packages:
 *   node scripts/gen-mosaic-names.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const require = createRequire(path.join(root, 'packages/web/package.json'));
const vg = await import(require.resolve('@uwdata/vgplot'));
const specDir = path.join(root, 'packages/web/node_modules/@uwdata/mosaic-spec');
const { inputNames } = await import(path.join(specDir, 'src/config/inputs.js'));
const { transformNames } = await import(path.join(specDir, 'src/config/transforms.js'));
const version = JSON.parse(fs.readFileSync(path.join(root, 'packages/web/node_modules/@uwdata/vgplot/package.json'), 'utf8')).version;

const names = {
  marks: Object.keys(vg.markDirectives).sort(),
  attributes: Object.keys(vg.attributeDirectives).sort(),
  interactors: Object.keys(vg.interactorDirectives).sort(),
  legends: Object.keys(vg.legendDirectives).sort(),
  inputs: [...inputNames()].sort(),
  transforms: [...transformNames()].sort(),
  selections: ['crossfilter', 'intersect', 'single', 'union'],
};
const list = (arr) => arr.map((n) => `'${n}'`).join(', ');
const out = `// Generated by scripts/gen-mosaic-names.mjs from @uwdata/vgplot ${version} — do not edit.
/** The vocabulary of Mosaic declarative specs, used to validate specs server-side without the browser stack. */
export const MOSAIC_NAMES = {
  marks: new Set([${list(names.marks)}]),
  attributes: new Set([${list(names.attributes)}]),
  interactors: new Set([${list(names.interactors)}]),
  legends: new Set([${list(names.legends)}]),
  inputs: new Set([${list(names.inputs)}]),
  transforms: new Set([${list(names.transforms)}]),
  selections: new Set([${list(names.selections)}]),
} as const;
export const MOSAIC_VERSION = '${version}';
`;
const target = path.join(root, 'packages/server/src/services/mosaic-names.ts');
fs.writeFileSync(target, out);
console.log(`wrote ${path.relative(root, target)}: ${Object.entries(names).map(([k, v]) => `${k} ${v.length}`).join(', ')}`);
